#!/usr/bin/env python3
"""
s6_sensitivity.py -- Task 7 of the forecast: statistical and systematics-limited
sensitivity to the DM-induced rate, and its translation into mass reach and
minimum detectable halo fraction f (opaque Earth, every crossing recorded).

Reads (if present) outputs/s4_fisher_table.csv for the template information
r_eff / r_plain; otherwise uses the defaults stored in sensitivity_lib.py.

Outputs
  outputs/s6_sensitivity.csv        long table (one row per B, live time, case, eps, detector)
  outputs/s6_sensitivity_tables.md  ready-to-paste Markdown tables
  outputs/s6_summary.json

Run:  python3 s6_sensitivity.py      (< 1 s)
FORECAST under stated assumptions -- not an analysis of HXMT data.
"""
import csv
import json
import math
import os

import sensitivity_lib as S

OUT = S.OUT
os.makedirs(OUT, exist_ok=True)

CASES = [  # (key, label, nuisance model, template)
    ("ideal", "background perfectly known, full template (unrealistic reference)", "none", "full"),
    ("const", "statistics only: one free constant, full template", "const", "full"),
    ("E", "after marginalising model E, sidereal (node) template", "E", "node"),
    ("R", "after marginalising model R (recommended), node template", "R", "node"),
]
MASSES = [1e2, 1e4, 1e6, 1e8, 1e10]


def fmt(x):
    if x == 0:
        return "0"
    if 1e-2 <= abs(x) < 1e4:
        return f"{x:.3g}"
    return f"{x:.2e}"


def main():
    fis = S.load_fisher()
    rows = []
    for t_live, sel in S.LIVE_TIMES.items():
        for key, label, model, tmpl in CASES:
            r = fis.get((sel, model))
            if r is None or f"r_eff_{tmpl}" not in r:
                continue
            re_, rp = r[f"r_eff_{tmpl}"], r[f"r_plain_{tmpl}"]
            for B in S.BACKGROUNDS:
                for eps in S.EPS_LIST:
                    tot, stat, sys_ = S.sigma_S0(B, t_live, re_, rp, eps)
                    row = dict(live_time_s=t_live, selection=sel, case=key, case_label=label, B=B, eps=eps,
                               r_eff=re_, r_plain=rp, sigma_stat=stat, delta_sys=sys_, sigma_tot=tot,
                               UL90=S.Z90 * tot, disc5=S.Z5 * tot,
                               UL90_mean_rate=S.Z90 * tot * S.MEAN_T, disc5_modulated_rms=S.Z5 * tot * rp)
                    for det, a in S.A_EFF_CM2.items():
                        row[f"m_reach_UL90_{det}"] = S.mass_reach(S.Z90 * tot, a)
                        row[f"m_reach_5sig_{det}"] = S.mass_reach(S.Z5 * tot, a)
                    rows.append(row)
    with open(os.path.join(OUT, "s6_sensitivity.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r_ in rows:
            w.writerow({k: (f"{v:.5g}" if isinstance(v, float) else v) for k, v in r_.items()})

    get = lambda t, case, B, eps: next(r_ for r_ in rows if r_["live_time_s"] == t and r_["case"] == case
                                       and r_["B"] == B and r_["eps"] == eps)
    md = []
    md.append("<!-- generated by s6_sensitivity.py : FORECAST, not HXMT data -->\n")
    # ---- Table 1: rate sensitivity -------------------------------------
    for t_live, sel in S.LIVE_TIMES.items():
        md.append(f"\n**Rate sensitivity, live time {t_live:.1e} s ({sel}); S0 = unshadowed DM rate, counts/s**\n")
        md.append("| B (c/s) | case | r_eff | 1σ stat | 90% UL (stat) | 5σ (stat) | 90% UL, ε=1e-5 | 90% UL, ε=1e-4 | 90% UL, ε=1e-3 | 5σ, ε=1e-5 | 5σ, ε=1e-4 | 5σ, ε=1e-3 |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for B in S.BACKGROUNDS:
            for key, label, model, tmpl in CASES:
                try:
                    r0 = get(t_live, key, B, 0.0)
                except StopIteration:
                    continue
                cells = [fmt(B), key, f"{r0['r_eff']:.3f}", fmt(r0["sigma_stat"]), fmt(r0["UL90"]), fmt(r0["disc5"])]
                cells += [fmt(get(t_live, key, B, e)["UL90"]) for e in (1e-5, 1e-4, 1e-3)]
                cells += [fmt(get(t_live, key, B, e)["disc5"]) for e in (1e-5, 1e-4, 1e-3)]
                md.append("| " + " | ".join(cells) + " |")
    # ---- Table 2: mass reach -------------------------------------------
    for det in ("NaI", "CsI", "veto"):
        md.append(f"\n**Maximum mass reach for f = 1, detector set '{det}' (A_eff = {S.A_EFF_CM2[det]:.0f} cm², "
                  f"ρ<w>A = {S.flux_mass_product(S.A_EFF_CM2[det]):.3e} GeV/s); GeV**\n")
        md.append("| B (c/s) | live time (s) | case | 90% UL stat | 5σ stat | 90% UL ε=1e-5 | 90% UL ε=1e-4 | 90% UL ε=1e-3 | 5σ ε=1e-4 |")
        md.append("|---|---|---|---|---|---|---|---|---|")
        for B in S.BACKGROUNDS:
            for t_live in S.LIVE_TIMES:
                for key in ("const", "E", "R"):
                    try:
                        r0 = get(t_live, key, B, 0.0)
                    except StopIteration:
                        continue
                    cells = [fmt(B), f"{t_live:.1e}", key, fmt(r0[f"m_reach_UL90_{det}"]), fmt(r0[f"m_reach_5sig_{det}"])]
                    cells += [fmt(get(t_live, key, B, e)[f"m_reach_UL90_{det}"]) for e in (1e-5, 1e-4, 1e-3)]
                    cells += [fmt(get(t_live, key, B, 1e-4)[f"m_reach_5sig_{det}"])]
                    md.append("| " + " | ".join(cells) + " |")
    # ---- Table 3: minimum detectable f ----------------------------------
    md.append("\n**Minimum detectable halo fraction f (5σ discovery threshold; in brackets: 90% UL), model R, node template**\n")
    md.append("| detector, B, live time | ε | m=1e2 GeV | 1e4 | 1e6 | 1e8 | 1e10 |")
    md.append("|---|---|---|---|---|---|---|")
    fmin_rows = []
    for det, B in (("NaI", 500.0), ("NaI", 100.0), ("NaI", 10.0), ("CsI", 8000.0), ("CsI", 2000.0)):
        for t_live in S.LIVE_TIMES:
            for eps in S.EPS_LIST:
                r0 = get(t_live, "R", B, eps)
                vals5 = [S.f_min(r0["disc5"], m, S.A_EFF_CM2[det]) for m in MASSES]
                vals90 = [S.f_min(r0["UL90"], m, S.A_EFF_CM2[det]) for m in MASSES]
                fmin_rows.append(dict(detector=det, B=B, live_time_s=t_live, eps=eps, f_min_5sigma=vals5, f_min_UL90=vals90))
                md.append(f"| {det}, B={fmt(B)}, t={t_live:.1e} | {eps:g} | " +
                          " | ".join(f"{a:.1e} ({b:.1e})" for a, b in zip(vals5, vals90)) + " |")
    # ---- Table 4: flux limits -------------------------------------------
    md.append("\n**Flux-limited masses for f = 1 (no background model needed)**\n")
    md.append("| detector set | A_eff (cm²) | live time (s) | 'one event' mass (GeV) | 2.3 events (90% CL, zero background) | raw-rate mass for B (GeV) |")
    md.append("|---|---|---|---|---|---|")
    flux_rows = []
    for det, B in (("NaI", 500.0), ("CsI", 8000.0), ("veto", 2000.0)):
        for t_live in S.LIVE_TIMES:
            a = S.A_EFF_CM2[det]
            m1 = S.one_event_mass(a, t_live)
            m23 = S.one_event_mass(a, t_live, 2.303)
            mr = S.raw_rate_mass(B, a)
            flux_rows.append(dict(detector=det, A_eff=a, live_time_s=t_live, one_event_mass=m1, m_2p3_events=m23,
                                  raw_rate_B=B, raw_rate_mass=mr))
            md.append(f"| {det} | {a:.0f} | {t_live:.1e} | {m1:.2e} | {m23:.2e} | {mr:.2e} (B = {fmt(B)} c/s) |")
    with open(os.path.join(OUT, "s6_sensitivity_tables.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")

    som, dep, lv = S.load_earth_opacity()
    summary = dict(
        assumptions=dict(rho=S.RHO_DM, mean_speed_kms=S.MEAN_SPEED_KMS, mean_T=S.MEAN_T, A_eff_cm2=S.A_EFF_CM2,
                         flux_mass_product_GeV_per_s={k: S.flux_mass_product(v) for k, v in S.A_EFF_CM2.items()},
                         sigma_min=S.SIGMA_MIN, self_shield_sigma_over_m=S.SELF_SHIELD_SIGMA_OVER_M,
                         atm_ceiling_sigma_over_m=S.ATM_CEILING_SIGMA_OVER_M, earth_opacity_sigma_over_m=lv,
                         z90=S.Z90, z5=S.Z5, backgrounds=S.BKG_MEANING),
        fisher_inputs={f"{k[0]} | {k[1]}": v for k, v in fis.items()},
        f_min=fmin_rows, flux_limits=flux_rows,
        p3_check=dict(B=500.0, t=2.0e8, five_sigma_rms_modulated_rate=5 * math.sqrt(500.0 / 2.0e8),
                      five_sigma_S0_const=5 * math.sqrt(500.0 / 2.0e8) / fis[("all non-SAA", "const")]["r_eff_full"],
                      five_sigma_S0_modelE_node=5 * math.sqrt(500.0 / 2.0e8) / fis[("all non-SAA", "E")]["r_eff_node"],
                      five_sigma_S0_modelR_node=5 * math.sqrt(500.0 / 2.0e8) / fis[("all non-SAA", "R")]["r_eff_node"]))
    summary["p3_check"]["mass_reach_5sigma_NaI_modelR"] = S.mass_reach(summary["p3_check"]["five_sigma_S0_modelR_node"], S.A_EFF_CM2["NaI"])
    summary["p3_check"]["mass_reach_5sigma_NaI_const"] = S.mass_reach(summary["p3_check"]["five_sigma_S0_const"], S.A_EFF_CM2["NaI"])
    with open(os.path.join(OUT, "s6_summary.json"), "w") as f:
        json.dump(summary, f, indent=1)
    print("\n".join(md))
    print(json.dumps(summary["p3_check"], indent=1))


if __name__ == "__main__":
    main()
